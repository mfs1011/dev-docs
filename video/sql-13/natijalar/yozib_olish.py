#!/usr/bin/env python3
import subprocess, json, os

PG_ENV = dict(os.environ, PGPASSFILE="/Users/mfsv/Projects/experiment/sql-sinov/pgpass")
PG_CMD = ["psql", "-h", "localhost", "-p", "5432", "-U", "postgres", "-d", "postgres", "-X"]
MY_CMD = ["mysql", "--defaults-extra-file=/Users/mfsv/Projects/experiment/sql-sinov/talaba.cnf", "qollanma", "-e"]
SQLITE_BIN = "/Users/mfsv/Projects/experiment/sql-sinov/bin/sqlite3"

def run_pg(sql):
    p = subprocess.run(PG_CMD, input=sql, text=True, capture_output=True, env=PG_ENV)
    return (p.stdout + p.stderr).strip()

def run_my(sql):
    p = subprocess.run(MY_CMD + [sql], capture_output=True, text=True)
    return (p.stdout + p.stderr).strip()

def run_sqlite(sql):
    p = subprocess.run([SQLITE_BIN, "-box", ":memory:"], input=sql, text=True, capture_output=True)
    return (p.stdout + p.stderr).strip()

out = {"pg": {}, "mysql": {}, "sqlite": {}}

print("PostgreSQL 18.6 sinovlari...")
out["pg"]["always_err"] = run_pg("""
DROP TABLE IF EXISTS mijozlar CASCADE;
CREATE TABLE mijozlar (
    id  bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ism text NOT NULL
);
INSERT INTO mijozlar (ism) VALUES ('Ali'), ('Vali');
INSERT INTO mijozlar (id, ism) VALUES (10, 'Sobir');
""")

out["pg"]["always_override"] = run_pg("""
INSERT INTO mijozlar (id, ism) OVERRIDING SYSTEM VALUE VALUES (10, 'Sobir');
SELECT * FROM mijozlar ORDER BY id;
""")

out["pg"]["by_default"] = run_pg("""
DROP TABLE IF EXISTS mijozlar_def CASCADE;
CREATE TABLE mijozlar_def (
    id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ism text NOT NULL
);
INSERT INTO mijozlar_def (ism) VALUES ('Ali');
INSERT INTO mijozlar_def (id, ism) VALUES (10, 'Sobir');
INSERT INTO mijozlar_def (ism) VALUES ('Vali');
SELECT * FROM mijozlar_def ORDER BY id;
""")

out["pg"]["serial_seq"] = run_pg("""
DROP TABLE IF EXISTS eski CASCADE;
CREATE TABLE eski (id serial PRIMARY KEY, ism text);
SELECT pg_get_serial_sequence('eski', 'id');
SELECT nextval('eski_id_seq') AS n1, nextval('eski_id_seq') AS n2, currval('eski_id_seq') AS c;
DROP TABLE eski CASCADE;
""")

out["pg"]["gap_demo"] = run_pg("""
BEGIN;
INSERT INTO mijozlar (ism) VALUES ('BekorQilingan');
ROLLBACK;
INSERT INTO mijozlar (ism) VALUES ('Keyingi');
SELECT * FROM mijozlar ORDER BY id;
DROP TABLE IF EXISTS mijozlar, mijozlar_def CASCADE;
""")

print("MySQL 9.7 sinovlari...")
out["mysql"]["auto_demo"] = run_my("""
DROP TABLE IF EXISTS mijozlar_my;
CREATE TABLE mijozlar_my (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    ism VARCHAR(30) NOT NULL
);
INSERT INTO mijozlar_my (ism) VALUES ('Ali'), ('Vali');
SELECT LAST_INSERT_ID();
INSERT INTO mijozlar_my (id, ism) VALUES (0, 'Nol'), (NULL, 'Null');
INSERT INTO mijozlar_my (id, ism) VALUES (100, 'Sobir');
INSERT INTO mijozlar_my (ism) VALUES ('Keyingi');
SELECT * FROM mijozlar_my ORDER BY id;
DROP TABLE mijozlar_my;
""")

out["mysql"]["tinyint_err"] = run_my("""
DROP TABLE IF EXISTS kichik;
CREATE TABLE kichik (id TINYINT AUTO_INCREMENT PRIMARY KEY, x INT);
INSERT INTO kichik (id, x) VALUES (127, 1);
INSERT INTO kichik (x) VALUES (2);
""")

print("SQLite sinovlari...")
out["sqlite"]["autoincrement_demo"] = run_sqlite("""
CREATE TABLE oddiy (id INTEGER PRIMARY KEY, ism TEXT);
CREATE TABLE auto  (id INTEGER PRIMARY KEY AUTOINCREMENT, ism TEXT);
INSERT INTO oddiy (ism) VALUES ('Ali'), ('Vali'), ('Sobir');
INSERT INTO auto  (ism) VALUES ('Ali'), ('Vali'), ('Sobir');
DELETE FROM oddiy WHERE id = 3;
DELETE FROM auto  WHERE id = 3;
INSERT INTO oddiy (ism) VALUES ('Yangi');
INSERT INTO auto  (ism) VALUES ('Yangi');
SELECT 'oddiy' AS jadval, id, ism FROM oddiy
UNION ALL
SELECT 'auto', id, ism FROM auto;
SELECT * FROM sqlite_sequence;
""")

print("Natijalar tty.js ga yozilmoqda...")
with open("tty.js", "w") as f:
    f.write("(function (g) {\n")
    f.write("  g.TTY = ")
    f.write(json.dumps(out, indent=2, ensure_ascii=False))
    f.write(";\n")
    f.write("})(typeof window !== 'undefined' ? window : globalThis);\n")

print("Tayyor!")

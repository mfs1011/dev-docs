/** MONITOR hodisasidan argumentlar: xizmat ularni aniq ro'yxat qilib yuboradi (x.args); matn berilsa — probel bo'yicha */
export function argumentlar(x) {
  if (x && typeof x === 'object') return x.args ?? argumentlar(x.qator ?? '')
  return String(x ?? '').trim().split(/\s+/).filter(Boolean)
}
export const buyruqNomi = (x) => (argumentlar(x)[0] ?? '').toUpperCase()
